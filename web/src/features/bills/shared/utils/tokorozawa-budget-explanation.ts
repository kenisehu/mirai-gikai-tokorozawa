export function getTokorozawaBudgetExplanation(
  metadata?: Pick<
    MunicipalBillMetadata,
    "municipality_name" | "meeting_name" | "bill_number"
  >
): string | null {
  if (
    metadata?.municipality_name !== "所沢市" ||
    metadata.meeting_name !== "令和8年第5回(9月)定例会議市長提出議案"
  ) {
    return null;
  }
  const content = EXPLANATIONS[metadata.bill_number ?? ""];
  return content
    ? `${content}\n\n資料確認日：2026年9月15日。市の資料に基づく非公式の解説です。採決結果はこのページの審議状況・公式結果を確認してください。`
    : null;
}
